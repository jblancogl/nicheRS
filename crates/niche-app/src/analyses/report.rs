//! Printable page of each decision-support analysis (`report.html`): what it answers and what
//! it does not, the method, tables, maps embedded as PNG data URIs, references and the mandatory
//! disclaimer. Same layout and rules as the species report (`report_html.rs`, ADR-0007).

use std::fmt::Write;

use niche_geo::{Raster, colormap, tiles};

use super::DISCLAIMER;
use crate::dto::{
    Analysis, ComparisonResult, FootprintResult, JobSpec, PriorityResult, RichnessResult,
};
use crate::report_html::{STYLE, base64, esc, fmt_num};

const MAP_MAX_PX: usize = 1200;

/// A map of the page: a raster with its colouring, caption and legend (HTML).
pub struct Figure<'a> {
    pub raster: &'a Raster,
    pub style: &'a dyn Fn(f32) -> Option<[u8; 4]>,
    pub caption: String,
    pub legend: String,
}

fn figure(f: &Figure<'_>) -> String {
    let s = f.raster.spec;
    let scale = s.width.max(s.height) as f64 / MAP_MAX_PX as f64;
    let w = ((s.width as f64 / scale).floor() as usize).max(1);
    let h = ((s.height as f64 / scale).floor() as usize).max(1);
    let mut rgba = vec![0u8; w * h * 4];
    for py in 0..h {
        let r = (((py as f64 + 0.5) * scale) as usize).min(s.height - 1);
        for px in 0..w {
            let c = (((px as f64 + 0.5) * scale) as usize).min(s.width - 1);
            let v = f.raster.data[r * s.width + c];
            if v.is_nan() {
                continue;
            }
            if let Some(col) = (f.style)(v) {
                rgba[(py * w + px) * 4..(py * w + px) * 4 + 4].copy_from_slice(&col);
            }
        }
    }
    let png = tiles::encode_image(w as u32, h as u32, &rgba);
    format!(
        "<figure><img class=\"map\" alt=\"{}\" src=\"data:image/png;base64,{}\"><figcaption>{} {}</figcaption></figure>",
        esc(&f.caption),
        base64(&png),
        esc(&f.caption),
        f.legend
    )
}

fn swatch(c: [u8; 3]) -> String {
    format!(
        "<span style=\"display:inline-block;width:3mm;height:3mm;vertical-align:middle;background:rgb({},{},{})\"></span>",
        c[0], c[1], c[2]
    )
}

fn pct(x: f64) -> String {
    format!("{:.1} %", x * 100.0)
}

fn level(l: Option<crate::dto::EvidenceLevel>) -> String {
    l.map_or_else(|| "–".into(), |l| format!("{l:?}"))
}

pub fn html(a: &Analysis, spec: &JobSpec, figures: &[Figure<'_>]) -> String {
    let mut s = String::new();
    let _ = write!(
        s,
        "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\"><title>{}</title><style>{STYLE}</style></head><body><main>",
        esc(&a.title)
    );
    let _ = write!(
        s,
        "<h1>{}</h1><p class=\"meta\">Study: {} · Study area: {} · Study id: {} · Analysis id: {} · Generated by NicheRS {} on {}</p>",
        esc(&a.title),
        esc(&spec.name),
        esc(&spec.area.name),
        esc(&a.job_id),
        esc(&a.id),
        env!("CARGO_PKG_VERSION"),
        jiff::Timestamp::now().strftime("%Y-%m-%d %H:%M UTC"),
    );
    if a.synthetic {
        s.push_str("<p class=\"banner\">SYNTHETIC DEMONSTRATION DATA — not a real species, place or project. Do not use for any decision.</p>");
    }
    let _ = write!(s, "<p class=\"notice\">{}</p>", esc(DISCLAIMER));
    if let Some(p) = &a.priority {
        priority(&mut s, p);
    }
    if let Some(f) = &a.footprint {
        footprint(&mut s, f);
    }
    if let Some(r) = &a.richness {
        richness(&mut s, r);
    }
    if let Some(c) = &a.comparison {
        comparison(&mut s, c);
    }
    if !figures.is_empty() {
        s.push_str("<h2>Maps</h2>");
        for f in figures {
            s.push_str(&figure(f));
        }
    }
    if !a.warnings.is_empty() {
        s.push_str("<h2>Warnings</h2><ul class=\"warn\">");
        for w in &a.warnings {
            let _ = write!(s, "<li><b>{:?}</b>: {}</li>", w.severity, esc(&w.message));
        }
        s.push_str("</ul>");
    }
    s.push_str("<h2>References</h2><ul class=\"cite\">");
    for r in references(&a.kind) {
        let _ = write!(s, "<li>{}</li>", esc(r));
    }
    s.push_str("</ul>");
    s.push_str("<h2>Traceability</h2><p>This page, its files and their checksums are listed in the analysis manifest (<code>manifest.json</code>), which also records the checksum of the study's execution manifest and of every study file read. The study's own outputs were not changed.</p>");
    s.push_str("</main></body></html>");
    s
}


//! Bias and cleaning options of Science v1 phase 2 on the synthetic demo: distance thinning,
//! target-group background (ADR-0013) with its synthetic effort surface, the fallback when the
//! target group is unavailable, bias-matched null models and the manifest. Default
//! specifications must stay bit-identical.

use std::collections::BTreeMap;
use std::sync::atomic::AtomicBool;

use niche_app::dto::*;
use niche_app::{Config, Engine, demo};

fn cfg(dir: &std::path::Path) -> Config {
    Config {
        data_dir: dir.join("data"),
        cache_dir: dir.join("cache"),
        max_records: 5000,
        gbif: None,
        secret_key: None,
        mirror: None,
        limits: Default::default(),
        retention_days: 0,
    }
}

fn root(name: &str) -> std::path::PathBuf {
    let d = std::env::temp_dir().join(format!("niche-bias-opts-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&d);
    d
}

/// A small, fast demo study (one fixed setting, coarser grid).
fn spec(
    filters: OccurrenceFilters,
    model: ModelSettings,
    validation: ValidationSettings,
) -> JobSpec {
    JobSpec {
        name: "bias options".into(),
        species: vec![SpeciesRef {
            key: 0,
            scientific_name: demo::SPECIES_NAME.into(),
            own: None,
        }],
        area: StudyArea {
            name: "Demo".into(),
            geometry: demo::area_geojson(),
            places: vec![],
        },
        layers: demo::LAYERS.iter().map(|l| l.0.to_string()).collect(),
        resolution_factor: 2,
        filters,
        model: ModelSettings {
            tuning: "fixed".into(),
            feature_classes: vec!["LQ".into()],
            beta_multipliers: vec![1.0],
            background_points: 2000,
            ..model
        },
        validation,
        seed: 5,
        demo: true,
        projections: vec![],
        own_dataset: None,
    }
}

type Files = BTreeMap<String, Vec<u8>>;

/// Run a spec to completion; returns the engine, job id, species result and output files
/// (report generation times removed).
fn run(dir: &std::path::Path, spec: JobSpec) -> (Engine, String, SpeciesResult, Files) {
    let e = Engine::open(cfg(dir)).expect("engine");
    let id = e.submit(spec).expect("submit").id;
    let never = AtomicBool::new(false);
    e.run_job(&id, &never, &never);
    let res = e.results(&id).expect("results");
    assert_eq!(res.job.status, JobStatus::Succeeded, "{:?}", res.job.error);
    let r = res.species[0].clone();
    assert_eq!(r.status, SpeciesRunStatus::Succeeded, "{:?}", r.error);
    let files = std::fs::read_dir(dir.join("data/jobs").join(&id).join("0"))
        .expect("species dir")
        .flatten()
        .map(|e| {
            let name = e.file_name().to_string_lossy().into_owned();
            let mut bytes = std::fs::read(e.path()).expect("read");
            if name == "report.md" || name == "report.html" {
                let text = String::from_utf8(bytes).expect("utf-8");
                bytes = text
                    .lines()
                    .filter(|l| !l.starts_with("Generated by NicheRS"))
                    .map(|l| {
                        match (
                            l.find(" · Generated by NicheRS"),
                            l.find(" · GBIF taxon key"),
                        ) {
                            (Some(a), Some(b)) if a < b => format!("{}{}", &l[..a], &l[b..]),
                            _ => l.to_string(),
                        }
                    })
                    .collect::<Vec<_>>()
                    .join("\n")
                    .into_bytes();
            }
            (name, bytes)
        })
        .collect();
    (e, id, r, files)
}

fn text(f: &Files, name: &str) -> String {
    String::from_utf8(f[name].clone()).expect("utf-8")
}

#[test]
fn default_settings_are_bit_identical_to_explicitly_disabled_options() {
    let dir = root("default");
    // Pre-phase-2 wire forms and the same settings with every new option written as "off".
    let old_f: OccurrenceFilters = serde_json::from_str(r#"{"year_min":1981}"#).expect("filters");
    let explicit_f: OccurrenceFilters =
        serde_json::from_str(r#"{"year_min":1981,"thin_km":null}"#).expect("filters");
    let old_m: ModelSettings = serde_json::from_str(r#"{"tuning":"auto"}"#).expect("model");
    let explicit_m: ModelSettings = serde_json::from_str(
        r#"{"tuning":"auto","background_method":"random","target_group":null}"#,
    )
    .expect("model");
    assert_eq!(old_f, OccurrenceFilters::default());
    assert_eq!(explicit_f, old_f);
    assert_eq!(old_m, ModelSettings::default());
    assert_eq!(explicit_m, old_m);
    // No new key in the serialized defaults, hence the same specification hash as before.
    let fj = serde_json::to_string(&explicit_f).expect("json");
    let mj = serde_json::to_string(&explicit_m).expect("json");
    assert!(!fj.contains("thin_km"), "{fj}");
    assert!(
        !mj.contains("background_method") && !mj.contains("target_group"),
        "{mj}"
    );

    let (_, _, a, fa) = run(
        &dir.join("a"),
        spec(old_f, old_m, ValidationSettings::default()),
    );
    let (_, _, b, fb) = run(
        &dir.join("b"),
        spec(explicit_f, explicit_m, ValidationSettings::default()),
    );
    assert_eq!(a, b);
    assert_eq!(fa.keys().collect::<Vec<_>>(), fb.keys().collect::<Vec<_>>());
    for (name, bytes) in &fa {
        assert!(fb[name] == *bytes, "{name} differs");
    }
    // Nothing of the new options in a default result or report.
    let json = text(&fa, "result.json");
    for key in [
        "\"background_sampling\":",
        "\"sampling_bias\":",
        "\"generalised\":",
        "\"effort\":",
        "Thinned",
    ] {
        assert!(!json.contains(key), "{key} in a default result");
    }
    assert!(!fa.contains_key("effort.tif"));
    assert!(text(&fa, "report.md").contains("no bias correction was applied"));
    assert!(text(&fa, "report.html").contains("no bias correction was applied"));
    assert!(
        !text(&fa, "report.md").contains("SINP"),
        "synthetic data: no SINP note"
    );
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn distance_thinning_is_deterministic_and_reported() {
    let dir = root("thin");
    let thin = OccurrenceFilters {
        thin_km: Some(8.0),
        ..OccurrenceFilters::default()
    };
    let (e, id, a, fa) = run(
        &dir.join("a"),
        spec(
            thin.clone(),
            ModelSettings::default(),
            ValidationSettings::default(),
        ),
    );
    let (_, _, b, fb) = run(
        &dir.join("b"),
        spec(
            thin,
            ModelSettings::default(),
            ValidationSettings::default(),
        ),
    );
    let (_, _, plain, _) = run(
        &dir.join("c"),
        spec(
            OccurrenceFilters::default(),
            ModelSettings::default(),
            ValidationSettings::default(),
        ),
    );
    // Same seed, same thinning, same model.
    assert_eq!(a, b);
    assert!(fa["suitability.tif"] == fb["suitability.tif"]);
    let thinned = a
        .data
        .exclusions
        .iter()
        .find(|x| x.reason == "Thinned (closer than 8 km to a retained record)")
        .map(|x| x.count)
        .expect("thinning reason");
    assert!(thinned > 0);
    assert_eq!(a.data.presences + thinned, plain.data.presences);
    // Thinned records are in the occurrences with their own status.
    let pts = e.occurrences(&id, 0).expect("occurrences");
    assert_eq!(
        pts.iter().filter(|p| p.status == "thinned").count(),
        thinned
    );
    assert!(
        text(&fa, "report.md").contains("Distance thinning: presence cells at least 8 km apart")
    );
    assert!(text(&fa, "report.md").contains("Aiello-Lammens"));
    let m = e.manifest(&id).expect("manifest");
    assert!(
        m["methods"]["thinning"]
            .as_str()
            .expect("thinning")
            .contains("8 km")
    );
    assert_eq!(m["spec"]["filters"]["thin_km"], 8.0);
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn target_group_background_on_the_demo_with_bias_matched_nulls() {
    let dir = root("target");
    let tg = ModelSettings {
        background_method: "target_group".into(),
        ..ModelSettings::default()
    };
    let nulls = ValidationSettings {
        null_models: 19,
        ..ValidationSettings::default()
    };
    let (e, id, r, files) = run(&dir, spec(OccurrenceFilters::default(), tg, nulls));
    let b = r.background_sampling.clone().expect("background sampling");
    assert_eq!(
        (b.requested.as_str(), b.method.as_str()),
        ("target_group", "target_group")
    );
    assert_eq!(b.target_group.as_deref(), Some(niche_app::bias::DEMO_CLASS));
    assert!(b.synthetic && b.fallback_reason.is_none());
    assert!(b.eligible_cells >= 1000);
    assert_eq!(r.data.background, 2000);
    // Bias diagnostic and its effort layer.
    let d = r.sampling_bias.clone().expect("sampling bias");
    assert!(d.synthetic && d.records > 0 && d.max_cell_records > 0.0);
    assert_eq!(d.cells_with_effort, b.eligible_cells);
    assert!((0.0..=1.0).contains(&d.presences_in_top10pct_effort_cells));
    assert!((0.09..0.2).contains(&d.expected), "{}", d.expected);
    assert!(files.contains_key("effort.tif"));
    assert!(r.warnings.iter().any(|w| w.code == "effort_concentration"));
    let sb = r
        .warnings
        .iter()
        .find(|w| w.code == "sampling_bias")
        .expect("sampling_bias warning");
    assert_eq!(sb.params["method"], "target_group");
    // The effort layer is served and sampled.
    assert!(e.raster(&id, 0, "effort").is_ok());
    assert_eq!(e.effort_max(&id, 0).expect("max"), d.max_cell_records);
    let (x, y) = (4.85, 45.6); // a synthetic "town"
    assert!(
        e.sample(&id, 0, x, y)
            .expect("sample")
            .effort
            .is_some_and(|v| v > 0.0)
    );
    // Bias-matched null models.
    let nm = r.validation.null_model.clone().expect("null models");
    assert_eq!(nm.sampling, "effort_weighted");
    assert_eq!(nm.completed, 19);
    // Reports: the method, the diagnostic, and an accurate bias sentence with references.
    let md = text(&files, "report.md");
    assert!(md.contains("target-group background, Phillips et al. 2009"));
    assert!(md.contains("Sampling-bias diagnostic"));
    assert!(!md.contains("no bias correction was applied"));
    assert!(md.contains("Barber, R.A. et al. (2022)") && md.contains("Vollering"));
    assert!(md.contains("Bohl, C.L., Kass, J.M. & Anderson, R.P. (2019)"));
    let html = text(&files, "report.html");
    assert!(html.contains("Sampling effort") && !html.contains("no bias correction was applied"));
    // Manifest: method and per-species background and diagnostic; synthetic data have no
    // generalisation fields.
    let m = e.manifest(&id).expect("manifest");
    assert!(
        m["methods"]["background"]
            .as_str()
            .expect("bg")
            .starts_with("target group")
    );
    assert_eq!(m["spec"]["model"]["background_method"], "target_group");
    assert_eq!(m["species"][0]["background"]["method"], "target_group");
    assert!(
        m["species"][0]["sampling_bias"]["records"]
            .as_u64()
            .is_some()
    );
    assert!(m["species"][0].get("generalised_excluded").is_none());
    assert!(
        m["methods"]["cleaning"]
            .as_str()
            .expect("cleaning")
            .contains("ADR-0011")
    );
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn unavailable_target_group_falls_back_to_the_random_background() {
    let dir = root("fallback");
    let aves = ModelSettings {
        background_method: "target_group".into(),
        target_group: Some("Aves".into()),
        ..ModelSettings::default()
    };
    let (e, id, r, files) = run(
        &dir.join("a"),
        spec(
            OccurrenceFilters::default(),
            aves,
            ValidationSettings::default(),
        ),
    );
    let (_, _, random, rfiles) = run(
        &dir.join("b"),
        spec(
            OccurrenceFilters::default(),
            ModelSettings::default(),
            ValidationSettings::default(),
        ),
    );
    let b = r.background_sampling.clone().expect("background sampling");
    assert_eq!(b.method, "random");
    assert_eq!(b.target_group.as_deref(), Some("Aves"));
    assert!(
        b.fallback_reason
            .as_deref()
            .is_some_and(|x| x.contains("Aves"))
    );
    assert!(r.sampling_bias.is_none() && !files.contains_key("effort.tif"));
    let w = r
        .warnings
        .iter()
        .find(|w| w.code == "target_group_unavailable")
        .expect("fallback warning");
    assert_eq!(w.severity, Severity::Warning);
    // The fallback draws exactly the random background: the model is the default model.
    for f in [
        "suitability.tif",
        "uncertainty.tif",
        "mess.tif",
        "model.lambdas",
    ] {
        assert!(
            files[f] == rfiles[f],
            "{f} differs from the random-background run"
        );
    }
    assert_eq!(r.validation, random.validation);
    assert!(text(&files, "report.md").contains("no bias correction was applied"));
    let m = e.manifest(&id).expect("manifest");
    assert_eq!(m["species"][0]["background"]["method"], "random");
    let _ = std::fs::remove_dir_all(dir);
}

/// The regional mirror's effort grid (format 2, 30″ cells) lands in the right cells of a
/// coarser modelling grid: counts are summed per modelling cell, cells without predictor data
/// are ignored, other classes are not mixed in.
#[test]
fn mirror_effort_grid_is_summed_on_the_modelling_grid() {
    use std::io::Write;
    let dir = root("mirror-effort");
    std::fs::create_dir_all(&dir).expect("dir");
    let zip = dir.join("region.zip");
    let mut z = zip::ZipWriter::new(std::fs::File::create(&zip).expect("zip"));
    z.start_file("0001.csv", zip::write::SimpleFileOptions::default())
        .expect("entry");
    let head = "gbifID\tdatasetKey\tkingdom\tclass\tdecimalLatitude\tdecimalLongitude\tcoordinateUncertaintyInMeters\tyear\ttaxonKey\tspeciesKey\tbasisOfRecord\tlicense\n";
    let rows = [
        // Aves: 3 records in modelling cell A (two 30″ cells), 1 in cell B, 1 in an invalid cell.
        "1\tds\tAnimalia\tAves\t43.5960\t1.4001\t\t2020\t111\t111\tHUMAN_OBSERVATION\tCC0_1_0\n",
        "2\tds\tAnimalia\tAves\t43.5960\t1.4001\t\t2020\t111\t111\tHUMAN_OBSERVATION\tCC0_1_0\n",
        "3\tds\tAnimalia\tAves\t43.5990\t1.4090\t\t2020\t111\t111\tHUMAN_OBSERVATION\tCC0_1_0\n",
        "4\tds\tAnimalia\tAves\t43.4500\t1.6500\t\t2020\t111\t111\tHUMAN_OBSERVATION\tCC0_1_0\n",
        "5\tds\tAnimalia\tAves\t43.9500\t1.9500\t\t2020\t111\t111\tHUMAN_OBSERVATION\tCC0_1_0\n",
        // Another class in cell A: not part of the Aves target group.
        "6\tds\tPlantae\tMagnoliopsida\t43.5960\t1.4001\t\t2020\t333\t333\tHUMAN_OBSERVATION\tCC0_1_0\n",
    ];
    let mut body = head.to_string();
    for r in rows {
        body.push_str(r);
    }
    z.write_all(body.as_bytes()).expect("write");
    z.finish().expect("finish");
    let region = niche_data::gbif_mirror::region("fr-es").expect("region");
    let info = niche_data::gbif_download::DownloadInfo {
        key: "0000001-1".into(),
        doi: None,
        total_records: rows.len() as u64,
        created: jiff::Timestamp::now().to_string(),
        url: "https://www.gbif.org/occurrence/download/0000001".into(),
    };
    let snap = niche_data::gbif_mirror::MirrorDir::new(&dir.join("data"), &region)
        .install(
            &zip,
            &region,
            info,
            "2026-10-20T00:00:00Z",
            true,
            &|| false,
            &|_| {},
        )
        .expect("install");
    // Modelling grid: 1.0–2.0 °E, 43.0–44.0 °N in 0.25° cells; the north-east cell has no data.
    let spec = niche_geo::GridSpec {
        west: 1.0,
        north: 44.0,
        cell: 0.25,
        width: 4,
        height: 4,
    };
    let mut valid = vec![true; spec.len()];
    valid[spec.index(0, 3)] = false;
    let stack = niche_app::env::EnvStack {
        spec,
        area_mask: vec![true; spec.len()],
        land_mask: vec![true; spec.len()],
        valid,
        layers: vec![],
        row_area_km2: vec![1.0; 4],
        provenance: serde_json::Value::Null,
    };
    let points = snap
        .effort("Aves", (1.0, 43.0, 2.0, 44.0))
        .expect("read")
        .expect("Aves grid");
    let e = niche_app::bias::EffortSurface::from_points(&stack, "Aves", points, false);
    let a = spec.index(1, 1); // 1.25–1.50 °E, 43.50–43.75 °N
    let b = spec.index(2, 2); // 1.50–1.75 °E, 43.25–43.50 °N
    assert_eq!(e.counts[a], 3.0);
    assert_eq!(e.counts[b], 1.0);
    assert_eq!(e.counts.iter().sum::<f64>(), 4.0);
    assert_eq!(e.eligible_cells(&stack), 2);
    assert!(
        snap.effort("Mammalia", (1.0, 43.0, 2.0, 44.0))
            .expect("read")
            .is_none()
    );
    let _ = std::fs::remove_dir_all(dir);
}

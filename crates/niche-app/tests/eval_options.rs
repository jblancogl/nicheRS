//! Opt-in evaluation methods of ADR-0014 (Science v1 phase 3) on the synthetic demo: spatial grid
//! blocks sized by autocorrelation, null-model significance and the area of applicability.
//! Default specifications must stay bit-identical; options must not change the fitted model.

use std::collections::BTreeMap;
use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::Duration;

use niche_app::dto::*;
use niche_app::{Config, Engine, demo};

fn cfg(dir: &std::path::Path) -> Config {
    Config {
        data_dir: dir.join("data"),
        cache_dir: dir.join("cache"),
        max_records: 5000,
        gbif: None,
        secret_key: None,
        mirror: None,
        limits: Default::default(),
        retention_days: 0,
    }
}

fn root(name: &str) -> std::path::PathBuf {
    let d = std::env::temp_dir().join(format!("niche-eval-opts-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&d);
    d
}

/// A small, fast demo study (one fixed setting, coarser grid).
fn spec(validation: ValidationSettings) -> JobSpec {
    JobSpec {
        name: "evaluation options".into(),
        species: vec![SpeciesRef {
            key: 0,
            scientific_name: demo::SPECIES_NAME.into(),
            own: None,
        }],
        area: StudyArea {
            name: "Demo".into(),
            geometry: demo::area_geojson(),
            places: vec![],
        },
        layers: demo::LAYERS.iter().map(|l| l.0.to_string()).collect(),
        resolution_factor: 2,
        filters: OccurrenceFilters::default(),
        model: ModelSettings {
            tuning: "fixed".into(),
            feature_classes: vec!["LQ".into()],
            beta_multipliers: vec![1.0],
            background_points: 2000,
            ..ModelSettings::default()
        },
        validation,
        seed: 5,
        demo: true,
        projections: vec![],
        own_dataset: None,
    }
}

/// Run a spec to completion; returns its species result and output files (report generation
/// times removed, as they are the only content allowed to differ between runs).
fn run(dir: &std::path::Path, spec: JobSpec) -> (Engine, String, SpeciesResult, Files) {
    let e = Engine::open(cfg(dir)).expect("engine");
    let id = e.submit(spec).expect("submit").id;
    let never = AtomicBool::new(false);
    e.run_job(&id, &never, &never);
    let res = e.results(&id).expect("results");
    assert_eq!(res.job.status, JobStatus::Succeeded, "{:?}", res.job.error);
    let r = res.species[0].clone();
    assert_eq!(r.status, SpeciesRunStatus::Succeeded, "{:?}", r.error);
    let files = outputs(&dir.join("data/jobs").join(&id).join("0"));
    (e, id, r, files)
}

type Files = BTreeMap<String, Vec<u8>>;

fn outputs(dir: &std::path::Path) -> Files {
    std::fs::read_dir(dir)
        .expect("species dir")
        .flatten()
        .map(|e| {
            let name = e.file_name().to_string_lossy().into_owned();
            let mut bytes = std::fs::read(e.path()).expect("read");
            if name == "report.md" || name == "report.html" {
                let text = String::from_utf8(bytes).expect("utf-8");
                bytes = text
                    .lines()
                    .filter(|l| !l.starts_with("Generated by NicheRS"))
                    .map(|l| {
                        match (
                            l.find(" · Generated by NicheRS"),
                            l.find(" · GBIF taxon key"),
                        ) {
                            (Some(a), Some(b)) if a < b => format!("{}{}", &l[..a], &l[b..]),
                            _ => l.to_string(),
                        }
                    })
                    .collect::<Vec<_>>()
                    .join("\n")
                    .into_bytes();
            }
            (name, bytes)
        })
        .collect()
}

#[test]
fn default_settings_are_bit_identical_to_explicitly_disabled_options() {
    let dir = root("default");
    // The pre-ADR-0014 wire form and the same settings written with every new option off.
    let old: ValidationSettings =
        serde_json::from_str(r#"{"method":"spatial_block","folds":4}"#).expect("old form");
    let explicit: ValidationSettings = serde_json::from_str(
        r#"{"method":"spatial_block","folds":4,"block_km":null,"null_models":0,"aoa":false}"#,
    )
    .expect("explicit form");
    assert_eq!(old, ValidationSettings::default());
    assert_eq!(explicit, old);
    // Serialization (hence the spec hash) is unchanged: no new key when the options are off.
    assert_eq!(
        serde_json::to_string(&explicit).expect("json"),
        r#"{"method":"spatial_block","folds":4}"#
    );

    let (_, _, a, fa) = run(&dir.join("a"), spec(old));
    let (_, _, b, fb) = run(&dir.join("b"), spec(explicit));
    assert_eq!(a, b);
    assert_eq!(fa.keys().collect::<Vec<_>>(), fb.keys().collect::<Vec<_>>());
    for (name, bytes) in &fa {
        assert!(fb[name] == *bytes, "{name} differs");
    }
    // Nothing of the new methods appears in a default result.
    let json = String::from_utf8(fa["result.json"].clone()).expect("utf-8");
    for key in ["\"blocks\"", "\"null_model\"", "\"aoa\"", "aoa_"] {
        assert!(!json.contains(key), "{key} in a default result");
    }
    assert!(!fa.contains_key("aoa.tif"));
    assert!(a.validation.blocks.is_none() && a.validation.null_model.is_none() && a.aoa.is_none());
    assert!(!a.evidence.reasons.iter().any(|r| r.contains("null")));
    // The default method keeps 4 folds; a spatial_grid spec without `folds` gets 5.
    let grid: ValidationSettings =
        serde_json::from_str(r#"{"method":"spatial_grid"}"#).expect("grid");
    assert_eq!(grid.folds, 5);
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn grid_blocks_null_models_and_aoa_on_the_demo() {
    let dir = root("options");
    let grid = ValidationSettings {
        method: "spatial_grid".into(),
        folds: 5,
        ..ValidationSettings::default()
    };
    let t = std::time::Instant::now();
    let (_, _, plain, plain_files) = run(&dir.join("plain"), spec(grid.clone()));
    let t_plain = t.elapsed().as_secs_f64();
    let all = ValidationSettings {
        null_models: 19,
        aoa: true,
        ..grid.clone()
    };
    let t = std::time::Instant::now();
    let (e, id, r, files) = run(&dir.join("all"), spec(all));
    println!(
        "demo (factor 2): spatial_grid {t_plain:.1} s; + 19 null models + AOA {:.1} s",
        t.elapsed().as_secs_f64()
    );

    // Block design: automatic size within the documented band, folds recorded.
    let b = r.validation.blocks.as_ref().expect("block design");
    println!("blocks {b:?}");
    assert_eq!(b.chosen_by, "autocorrelation");
    assert_eq!(b.k_requested, 5);
    assert!(b.k_achieved >= 2 && b.k_achieved <= 5);
    assert_eq!(r.validation.folds.len(), b.k_achieved);
    let ac = b.autocorrelation.as_ref().expect("autocorrelation");
    assert!(ac.min_km >= 5.0 && ac.min_km <= ac.max_km);
    assert!(b.block_km >= ac.min_km && b.block_km <= ac.max_km);
    assert_eq!(ac.variables.len(), r.variables_used.len());
    assert_eq!(r.validation.method, "spatial_grid");

    // Null models: every replicate fitted, valid p-values.
    let nm = r.validation.null_model.as_ref().expect("null models");
    println!("null models {nm:?}");
    assert_eq!((nm.requested, nm.completed), (19, 19));
    assert_eq!(nm.presences, r.data.presences);
    assert_eq!(nm.sampling, "uniform");
    for st in [&nm.cbi, &nm.or10] {
        assert!(st.p_value > 0.0 && st.p_value <= 1.0);
        assert_eq!(st.n, 19);
    }
    assert_eq!(nm.cbi.observed, r.validation.cbi_mean);
    assert!(
        r.evidence
            .reasons
            .iter()
            .any(|x| x.contains("random-location null models")),
        "{:?}",
        r.evidence.reasons
    );

    // Area of applicability: layer written and served, summary consistent.
    let a = r.aoa.as_ref().expect("aoa");
    println!(
        "aoa threshold {:.3}, outside {:.3}",
        a.threshold, a.fraction_outside
    );
    assert!(a.threshold.is_finite() && a.threshold > 0.0);
    assert!((0.0..=1.0).contains(&a.fraction_outside));
    assert_eq!(a.n_train, r.data.presences + r.data.background);
    let wsum: f64 = a.weights.iter().map(|w| w.weight).sum();
    assert!((wsum - 1.0).abs() < 1e-9, "weights sum to {wsum}");
    assert!(r.files.iter().any(|f| f.name == "aoa.tif"));
    assert_eq!(
        r.warnings.iter().any(|w| w.code == "aoa_outside"),
        a.fraction_outside > 0.1
    );
    let raster = e.raster(&id, 0, "aoa").expect("aoa raster");
    let finite = raster.data.iter().filter(|v| v.is_finite()).count();
    assert!(finite > 0);
    assert!((e.aoa_threshold(&id, 0).expect("threshold") - a.threshold).abs() < 1e-12);
    let (lng, lat) = (4.5, 44.8);
    let s = e.sample(&id, 0, lng, lat).expect("sample");
    assert!(s.in_area && s.aoa_di.is_some());

    // Reports and manifest describe the methods.
    let md = String::from_utf8(files["report.md"].clone()).expect("utf-8");
    for t in [
        "## Spatial block design",
        "## Null models",
        "Area of applicability",
    ] {
        assert!(md.contains(t), "report.md lacks {t}");
    }
    let html = String::from_utf8(files["report.html"].clone()).expect("utf-8");
    for t in ["Spatial block design", "Null models", "Meyer, H."] {
        assert!(html.contains(t), "report.html lacks {t}");
    }
    assert!(!html.contains("confidence"));
    let m = e.manifest(&id).expect("manifest");
    assert_eq!(m["spec"]["validation"]["null_models"], 19);
    assert_eq!(m["spec"]["validation"]["aoa"], true);
    assert!(m["methods"]["null_models"].is_string());
    assert!(m["methods"]["area_of_applicability"].is_string());
    assert!(m["species"][0]["area_of_applicability"]["threshold"].is_number());
    assert!(m["species"][0]["validation"]["blocks"]["block_km"].is_number());

    // Null models and the AOA are evaluations: the fitted model and its maps are unchanged.
    for f in [
        "suitability.tif",
        "uncertainty.tif",
        "mess.tif",
        "model.lambdas",
    ] {
        assert!(
            plain_files[f] == files[f],
            "{f} changed by the evaluation options"
        );
    }
    assert_eq!(plain.validation.folds, r.validation.folds);
    assert_eq!(plain.thresholds, r.thresholds);
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn user_block_size_is_used_and_settings_are_validated() {
    let dir = root("user");
    let (e, _, r, _) = run(
        &dir.join("run"),
        spec(ValidationSettings {
            method: "spatial_grid".into(),
            folds: 3,
            block_km: Some(40.0),
            ..ValidationSettings::default()
        }),
    );
    let b = r.validation.blocks.expect("blocks");
    assert_eq!((b.chosen_by.as_str(), b.block_km), ("user", 40.0));
    assert!(b.autocorrelation.is_none());
    assert_eq!(b.k_requested, 3);

    let bad = |v: ValidationSettings| match e.submit(spec(v)) {
        Err(niche_app::AppError::Invalid(m)) => m,
        other => panic!("accepted: {other:?}"),
    };
    let base = ValidationSettings::default;
    assert!(
        bad(ValidationSettings {
            block_km: Some(20.0),
            ..base()
        })
        .contains("only to spatial_grid")
    );
    for km in [0.5, 5000.0, f64::NAN] {
        assert!(
            bad(ValidationSettings {
                method: "spatial_grid".into(),
                block_km: Some(km),
                ..base()
            })
            .contains("block size")
        );
    }
    assert!(
        bad(ValidationSettings {
            method: "spatial_grid".into(),
            folds: 1,
            ..base()
        })
        .contains("folds")
    );
    for n in [1, 18, 201] {
        assert!(
            bad(ValidationSettings {
                null_models: n,
                ..base()
            })
            .contains("null models")
        );
    }
    assert!(
        bad(ValidationSettings {
            method: "checkerboard".into(),
            ..base()
        })
        .contains("spatial_grid")
    );
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn null_models_interrupted_midway_resume_with_identical_results() {
    let dir = root("resume");
    let s = spec(ValidationSettings {
        null_models: 19,
        ..ValidationSettings::default()
    });
    let never = AtomicBool::new(false);
    let (_, _, _, reference) = run(&dir.join("reference"), s.clone());

    let d = dir.join("resumed");
    let id;
    let ckpt;
    {
        let e = Arc::new(Engine::open(cfg(&d)).expect("engine"));
        id = e.submit(s).expect("submit").id;
        ckpt = d.join("data/jobs").join(&id).join("checkpoints/0");
        let stop = Arc::new(AtomicBool::new(false));
        let (s2, c2) = (stop.clone(), ckpt.clone());
        let watcher = std::thread::spawn(move || {
            loop {
                let nulls = std::fs::read_dir(&c2)
                    .map(|d| {
                        d.flatten()
                            .filter(|e| e.file_name().to_string_lossy().starts_with("null-"))
                            .count()
                    })
                    .unwrap_or(0);
                if nulls >= 12 {
                    s2.store(true, Ordering::Relaxed);
                    return;
                }
                std::thread::sleep(Duration::from_millis(1));
            }
        });
        e.run_job(&id, &stop, &stop);
        watcher.join().expect("watcher");
        assert_eq!(
            e.store().get(&id).expect("db").expect("job").status,
            JobStatus::Running,
            "shutdown leaves the job resumable"
        );
    }
    assert!(ckpt.exists(), "null-model checkpoints kept for the resume");
    let e = Engine::open(cfg(&d)).expect("engine");
    e.store().recover_interrupted().expect("recover");
    e.run_job(&id, &never, &never);
    assert_eq!(
        e.results(&id).expect("results").job.status,
        JobStatus::Succeeded
    );
    let resumed = outputs(&d.join("data/jobs").join(&id).join("0"));
    assert_eq!(
        reference.keys().collect::<Vec<_>>(),
        resumed.keys().collect::<Vec<_>>()
    );
    for (name, bytes) in &reference {
        assert!(resumed[name] == *bytes, "{name} differs after resuming");
    }
    let _ = std::fs::remove_dir_all(dir);
}

/// Cost of the area of applicability at a realistic size (ADR-0014 costs): ≈ 10 000 background
/// and 150 presence rows × 7 correlated predictors, DI for 1 million cells (≈ metropolitan France's
/// land at 30″), parallel as in `fit.rs`. Synthetic values: three smooth latent factors of
/// position (as climate layers), without and with 10 % independent noise per variable (which
/// raises the intrinsic dimension and slows nearest-neighbour search). Run with
/// `cargo test --release -p niche-app --test eval_options -- --ignored --nocapture`.
#[test]
#[ignore = "timing measurement"]
fn aoa_timing_at_a_realistic_grid_size() {
    use rayon::prelude::*;
    // Deterministic pseudo-noise in [-0.5, 0.5) from an integer (splitmix64 finaliser).
    let hash = |mut z: u64| -> f64 {
        z = z.wrapping_add(0x9E37_79B9_7F4A_7C15);
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        (z ^ (z >> 31)) as f64 / u64::MAX as f64 - 0.5
    };
    for noise in [0.0, 0.1] {
        let row = |x: f64, y: f64, id: u64| -> Vec<f64> {
            let (a, b, c) = (
                (3.0 * x).sin() + y,
                (2.0 * y).cos() * x,
                (5.0 * x * y).sin(),
            );
            [
                a,
                0.8 * a + 0.2 * b,
                b,
                0.5 * b + 0.5 * c,
                c,
                a - c,
                0.3 * a + 0.3 * b + 0.4 * c,
            ]
            .iter()
            .enumerate()
            .map(|(v, val)| val + noise * hash(id * 8 + v as u64))
            .collect()
        };
        let mut rng = niche_eval::rng::Rng::new(1);
        let train: Vec<Vec<f64>> = (0..10_152u64)
            .map(|i| row(rng.uniform(), rng.uniform(), u64::MAX / 2 + i))
            .collect();
        let folds: Vec<usize> = (0..train.len()).map(|i| i % 5).collect();
        let weights = [0.3, 0.2, 0.15, 0.1, 0.1, 0.1, 0.05];
        let t = std::time::Instant::now();
        let aoa = niche_eval::Aoa::new(&train, Some(&weights), &folds, &mut rng).expect("aoa");
        let build = t.elapsed().as_secs_f64();
        let side = 1000usize;
        let t = std::time::Instant::now();
        let di: Vec<f64> = (0..side * side)
            .into_par_iter()
            .map_init(
                || vec![0.0; 7],
                |buf, i| {
                    let r = row(
                        (i / side) as f64 / side as f64,
                        (i % side) as f64 / side as f64,
                        i as u64,
                    );
                    buf.copy_from_slice(&r);
                    aoa.eval(buf)
                },
            )
            .collect();
        let query = t.elapsed().as_secs_f64();
        let outside = di.iter().filter(|d| **d > aoa.threshold()).count();
        println!(
            "AOA (noise {noise}): build {build:.2} s ({} training rows), DI of {} cells {query:.2} s on {} threads; {outside} outside",
            aoa.n_train(),
            di.len(),
            rayon::current_num_threads()
        );
    }
}

//! Future-climate projections (ADR-0016, Science v1 phase 5) on the synthetic demo, whose
//! "future" layers are SYNTHETIC (invented warming of the synthetic temperature and
//! precipitation; ruggedness static). Specifications without projections must stay
//! bit-identical; projections must run for MaxEnt, RF and the ensemble, give consistent areas,
//! resume after an interruption without refitting and with identical outputs, and reject
//! invalid scenarios. A live test with real CHELSA CMIP6 layers is `#[ignore]`d at the end.

use std::collections::BTreeMap;
use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::Duration;

use niche_app::dto::*;
use niche_app::{Config, Engine, demo, projection};

fn cfg(dir: &std::path::Path) -> Config {
    Config {
        data_dir: dir.join("data"),
        cache_dir: dir.join("cache"),
        max_records: 5000,
        gbif: None,
        secret_key: None,
        mirror: None,
        limits: Default::default(),
        retention_days: 0,
    }
}

fn root(name: &str) -> std::path::PathBuf {
    let d = std::env::temp_dir().join(format!("niche-proj-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&d);
    d
}

const ALL: [&str; 5] = [
    "GFDL-ESM4",
    "IPSL-CM6A-LR",
    "MPI-ESM1-2-HR",
    "MRI-ESM2-0",
    "UKESM1-0-LL",
];

fn scenario(period: &str, ssp: &str, gcms: &[&str]) -> ProjectionSpec {
    ProjectionSpec {
        period: period.into(),
        ssp: ssp.into(),
        gcms: gcms.iter().map(|g| (*g).to_string()).collect(),
    }
}

/// A small, fast demo study (one fixed MaxEnt setting, coarser grid).
fn spec(algorithm: &str, projections: Vec<ProjectionSpec>) -> JobSpec {
    JobSpec {
        name: "future climate".into(),
        species: vec![SpeciesRef {
            key: 0,
            scientific_name: demo::SPECIES_NAME.into(),
            own: None,
        }],
        area: StudyArea {
            name: "Demo".into(),
            geometry: demo::area_geojson(),
            places: vec![],
        },
        layers: demo::LAYERS.iter().map(|l| l.0.to_string()).collect(),
        resolution_factor: 2,
        filters: OccurrenceFilters::default(),
        model: ModelSettings {
            tuning: "fixed".into(),
            feature_classes: vec!["LQ".into()],
            beta_multipliers: vec![1.0],
            background_points: 2000,
            algorithm: algorithm.into(),
            rf_trees: (algorithm != "maxent").then_some(150),
            ..ModelSettings::default()
        },
        validation: ValidationSettings::default(),
        seed: 5,
        demo: true,
        projections,
        own_dataset: None,
    }
}

type Files = BTreeMap<String, Vec<u8>>;

/// Output files of a species, report generation times removed.
fn outputs(dir: &std::path::Path) -> Files {
    std::fs::read_dir(dir)
        .expect("species dir")
        .flatten()
        .map(|e| {
            let name = e.file_name().to_string_lossy().into_owned();
            let mut bytes = std::fs::read(e.path()).expect("read");
            if name == "report.md" || name == "report.html" {
                let text = String::from_utf8(bytes).expect("utf-8");
                bytes = text
                    .lines()
                    .filter(|l| !l.starts_with("Generated by NicheRS"))
                    .map(|l| {
                        match (
                            l.find(" · Generated by NicheRS"),
                            l.find(" · GBIF taxon key"),
                        ) {
                            (Some(a), Some(b)) if a < b => format!("{}{}", &l[..a], &l[b..]),
                            _ => l.to_string(),
                        }
                    })
                    .collect::<Vec<_>>()
                    .join("\n")
                    .into_bytes();
            }
            (name, bytes)
        })
        .collect()
}

fn run(dir: &std::path::Path, spec: JobSpec) -> (Engine, String, SpeciesResult, Files) {
    let e = Engine::open(cfg(dir)).expect("engine");
    let id = e.submit(spec).expect("submit").id;
    let never = AtomicBool::new(false);
    e.run_job(&id, &never, &never);
    let res = e.results(&id).expect("results");
    assert_eq!(res.job.status, JobStatus::Succeeded, "{:?}", res.job.error);
    let r = res.species[0].clone();
    assert_eq!(r.status, SpeciesRunStatus::Succeeded, "{:?}", r.error);
    let files = outputs(&dir.join("data/jobs").join(&id).join("0"));
    (e, id, r, files)
}

fn text(files: &Files, name: &str) -> String {
    String::from_utf8(files[name].clone()).expect("utf-8")
}

/// Consistency of one scenario's summary.
fn check_summary(p: &ProjectionResult, present_p10_km2: f64) {
    let close = |a: f64, b: f64| (a - b).abs() <= 1e-6 * b.abs().max(1.0);
    assert_eq!(
        p.cells_missing, 0,
        "synthetic future layers have every cell"
    );
    assert!(close(p.present_suitable_km2, present_p10_km2));
    assert!(close(p.stable_km2 + p.lost_km2, p.present_suitable_km2));
    assert!(close(p.stable_km2 + p.gained_km2, p.future_suitable_km2));
    assert!(p.stable_all_gcms_km2 <= p.stable_km2 + 1e-9);
    assert!(p.gained_all_gcms_km2 <= p.gained_km2 + 1e-9);
    assert!(p.lost_all_gcms_km2 <= p.lost_km2 + 1e-9);
    assert!((0.0..=1.0).contains(&p.novel_fraction));
    assert_eq!(p.per_gcm.len(), p.gcms.len());
    for g in &p.per_gcm {
        assert!((0.0..=1.0).contains(&g.mean_suitability));
        assert!(g.novel_fraction <= p.novel_fraction + 1e-12);
    }
    assert!(p.synthetic);
    assert_eq!(p.climate_variables, vec!["demo_temp", "demo_prec"]);
}

#[test]
fn specifications_without_projections_are_unchanged() {
    // Wire form: no key when empty, so the spec hash of existing studies is unchanged.
    let s = spec("maxent", vec![]);
    let json = serde_json::to_string(&s).expect("json");
    assert!(!json.contains("projections"), "{json}");
    let back: JobSpec = serde_json::from_str(&json).expect("old form");
    assert_eq!(back, s);

    let dir = root("default");
    let (e, id, r, files) = run(&dir, s);
    assert!(r.projections.is_empty());
    assert!(files.keys().all(|f| !f.starts_with("future_")));
    let result = text(&files, "result.json");
    assert!(!result.contains("\"projections\""));
    assert!(!text(&files, "report.md").contains("Future climate"));
    assert!(
        e.manifest(&id)
            .expect("manifest")
            .get("future_climate")
            .is_none()
    );
    let sample = e.sample(&id, 0, 4.5, 44.8).expect("sample");
    assert!(sample.projections.is_empty());
    assert!(
        !serde_json::to_string(&sample)
            .expect("json")
            .contains("projections")
    );

    // The same study with projections: the present outputs are byte-identical (the projection
    // only adds files and report sections).
    let (_, _, rp, with) = run(
        &dir.join("with"),
        spec(
            "maxent",
            vec![scenario("2041-2070", "ssp370", &["MPI-ESM1-2-HR"])],
        ),
    );
    for name in [
        "suitability.tif",
        "uncertainty.tif",
        "mess.tif",
        "model.lambdas",
        "response_curves.csv",
        "occurrences.geojson",
    ] {
        assert!(files[name] == with[name], "{name} changed by a projection");
    }
    assert_eq!(rp.thresholds, r.thresholds);
    assert_eq!(rp.validation, r.validation);
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn maxent_projections_on_the_demo() {
    let dir = root("maxent");
    let t = std::time::Instant::now();
    let (e, id, r, files) = run(
        &dir,
        spec(
            "maxent",
            vec![
                scenario("2041-2070", "ssp370", &ALL),
                scenario("2071-2100", "ssp585", &["GFDL-ESM4", "UKESM1-0-LL"]),
            ],
        ),
    );
    println!(
        "demo (factor 2), MaxEnt, 7 synthetic GCM runs: study {:.1} s",
        t.elapsed().as_secs_f64()
    );
    assert_eq!(r.projections.len(), 2);
    let p10 = r.thresholds.iter().find(|t| t.rule == "p10").expect("p10");
    for p in &r.projections {
        assert_eq!(p.threshold, p10.threshold);
        check_summary(p, p10.area_km2);
        println!(
            "{} {}: present {:.0} km², future {:.0} km² (stable {:.0}, gained {:.0}, lost {:.0}; all GCMs: {:.0}/{:.0}/{:.0}), SD {:.3}, MESS<0 {:.1} %",
            p.period,
            p.ssp,
            p.present_suitable_km2,
            p.future_suitable_km2,
            p.stable_km2,
            p.gained_km2,
            p.lost_km2,
            p.stable_all_gcms_km2,
            p.gained_all_gcms_km2,
            p.lost_all_gcms_km2,
            p.mean_gcm_sd,
            p.novel_fraction * 100.0
        );
    }
    // A strong synthetic warming moves conditions out of the training range.
    let hot = &r.projections[1];
    assert!(hot.novel_fraction > r.extrapolation.novel_fraction);
    assert!(
        r.warnings
            .iter()
            .any(|w| w.code == "projection_extrapolation")
    );
    // Ruggedness is static: said once.
    let w = r
        .warnings
        .iter()
        .filter(|w| w.code == "static_predictors_in_projection")
        .count();
    assert_eq!(
        w,
        usize::from(!r.projections[0].static_variables.is_empty())
    );
    // Files of each scenario, the areas table and descriptions saying synthetic.
    for p in &r.projections {
        for kind in projection::KINDS {
            let name = format!("{}.tif", projection::file_stem(&p.period, &p.ssp, kind));
            assert!(files.contains_key(&name), "{name}");
            let f = r.files.iter().find(|f| f.name == name).expect("listed");
            assert!(f.description.contains("SYNTHETIC"), "{}", f.description);
        }
    }
    let csv = text(&files, "future_areas.csv");
    assert_eq!(csv.lines().count(), 1 + 2 + 5 + 2);
    // Reports: section, synthetic label, limits and references.
    let md = text(&files, "report.md");
    for needle in [
        "## Future climate projections",
        "SYNTHETIC future scenarios",
        "No dispersal is modelled",
        "Elith, J., Kearney, M. & Phillips, S. (2010)",
        "Thuiller, W.",
        "| 2041-2070 | SSP3-7.0 (high emissions) | 5 |",
    ] {
        assert!(md.contains(needle), "report.md lacks {needle}");
    }
    assert!(!md.contains("range shift") || md.contains("not range shifts"));
    let html = text(&files, "report.html");
    assert!(
        html.contains("Future climate projections")
            && html.contains("Change in suitable conditions")
    );
    // Manifest: scenarios, synthetic source, no real URL.
    let m = e.manifest(&id).expect("manifest");
    let fc = &m["future_climate"];
    assert_eq!(fc["scenarios"].as_array().map(Vec::len), Some(2));
    assert!(
        fc["source"]
            .as_str()
            .is_some_and(|s| s.contains("SYNTHETIC"))
    );
    assert_eq!(fc["files"].as_array().map(Vec::len), Some(0));
    assert!(m["methods"]["projections"].is_string());
    assert_eq!(
        m["species"][0]["projections"].as_array().map(Vec::len),
        Some(2)
    );
    assert!(
        m["species"][0]["artifacts"]
            .get("future_2041-2070_ssp370_change.tif")
            .is_some()
    );
    // Tile rasters and point samples.
    let layer = projection::file_stem("2041-2070", "ssp370", "change");
    let change = e.raster(&id, 0, &layer).expect("change raster");
    let display = e
        .projection_change_display(&id, 0, &layer)
        .expect("display raster");
    let codes: std::collections::BTreeSet<u32> = change
        .data
        .iter()
        .filter(|v| v.is_finite())
        .map(|v| *v as u32)
        .collect();
    assert!(codes.iter().all(|c| (1..=4).contains(c)), "{codes:?}");
    assert!(display.data.iter().any(|v| *v >= 10.0));
    assert!(e.raster(&id, 0, "future_2041-2070_ssp245_mean").is_err());
    let s = e.sample(&id, 0, 4.5, 44.8).expect("sample");
    assert_eq!(s.projections.len(), 2);
    let ps = &s.projections[0];
    assert!(ps.mean.is_some() && ps.sd.is_some() && ps.mess.is_some());
    assert!(ps.change.is_some_and(|c| (1..=4).contains(&c)));
    assert!(ps.agreement.is_some_and(|a| a <= 5));
    let _ = std::fs::remove_dir_all(dir);
}


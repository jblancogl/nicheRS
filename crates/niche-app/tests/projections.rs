/// An ensemble study with projections stopped between two GCM runs (as by a server shutdown)
/// resumes without fitting again and gives byte-identical outputs.
#[test]
fn interrupted_projections_resume_with_identical_outputs() {
    let dir = root("resume");
    let s = spec(
        "ensemble",
        vec![
            scenario("2041-2070", "ssp370", &ALL),
            scenario("2071-2100", "ssp126", &ALL),
        ],
    );
    let never = AtomicBool::new(false);
    let (_, _, _, reference) = run(&dir.join("reference"), s.clone());

    let d = dir.join("resumed");
    let id;
    let ckpt;
    {
        let e = Arc::new(Engine::open(cfg(&d)).expect("engine"));
        id = e.submit(s).expect("submit").id;
        ckpt = d.join("data/jobs").join(&id).join("checkpoints/0");
        let stop = Arc::new(AtomicBool::new(false));
        let finished = Arc::new(AtomicBool::new(false));
        let (s2, f2, c2) = (stop.clone(), finished.clone(), ckpt.clone());
        // Stop once two GCM runs are saved.
        let watcher = std::thread::spawn(move || {
            while !f2.load(Ordering::Relaxed) {
                let runs = std::fs::read_dir(&c2)
                    .map(|d| {
                        d.flatten()
                            .filter(|e| e.file_name().to_string_lossy().starts_with("proj-"))
                            .count()
                    })
                    .unwrap_or(0);
                if runs >= 2 {
                    s2.store(true, Ordering::Relaxed);
                    return;
                }
                std::thread::sleep(Duration::from_micros(200));
            }
        });
        e.run_job(&id, &stop, &stop);
        finished.store(true, Ordering::Relaxed);
        watcher.join().expect("watcher");
        assert!(
            stop.load(Ordering::Relaxed),
            "the study was not interrupted"
        );
        assert_eq!(
            e.store().get(&id).expect("db").expect("job").status,
            JobStatus::Running,
            "shutdown leaves the job resumable"
        );
    }
    assert!(
        ckpt.join(projection::STATE).exists(),
        "projection state kept"
    );
    let species = d.join("data/jobs").join(&id).join("0");
    assert!(
        !species.join("result.json").exists(),
        "species not complete"
    );
    assert!(
        species.join("suitability.tif").exists(),
        "present outputs written"
    );
    let e = Engine::open(cfg(&d)).expect("engine");
    e.store().recover_interrupted().expect("recover");
    e.run_job(&id, &never, &never);
    let res = e.results(&id).expect("results");
    assert_eq!(res.job.status, JobStatus::Succeeded, "{:?}", res.job.error);
    let events = e.store().events_after(&id, 0).expect("events");
    assert!(
        events
            .iter()
            .any(|ev| ev.message.contains("resumed after the model fit")),
        "the fit was repeated"
    );
    assert!(
        events
            .iter()
            .any(|ev| ev.message.contains("taken from before the interruption")),
        "no GCM run reused"
    );
    assert!(!ckpt.exists(), "checkpoints cleared once complete");
    let resumed = outputs(&species);
    assert_eq!(
        reference.keys().collect::<Vec<_>>(),
        resumed.keys().collect::<Vec<_>>()
    );
    for (name, bytes) in &reference {
        if resumed[name] != *bytes && name.ends_with(".json") {
            let (a, b) = (text(&reference, name), text(&resumed, name));
            for (x, y) in a.lines().zip(b.lines()) {
                if x != y {
                    println!("- {x}\n+ {y}");
                }
            }
        }
        assert!(resumed[name] == *bytes, "{name} differs after resuming");
    }
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn invalid_projections_are_rejected() {
    let dir = root("invalid");
    let e = Engine::open(cfg(&dir)).expect("engine");
    let err = |p: Vec<ProjectionSpec>, layers: Option<Vec<&str>>| -> String {
        let mut s = spec("maxent", p);
        if let Some(l) = layers {
            s.layers = l.into_iter().map(String::from).collect();
        }
        match e.submit(s) {
            Err(niche_app::AppError::Invalid(m)) => m,
            other => panic!("accepted: {other:?}"),
        }
    };
    assert!(err(vec![scenario("2031-2060", "ssp370", &ALL)], None).contains("period"));
    assert!(err(vec![scenario("2041-2070", "ssp245", &ALL)], None).contains("scenario"));
    assert!(
        err(vec![scenario("2041-2070", "ssp370", &["CanESM5"])], None).contains("climate model")
    );
    assert!(err(vec![scenario("2041-2070", "ssp370", &[])], None).contains("at least one"));
    assert!(
        err(
            vec![scenario("2041-2070", "ssp370", &["GFDL-ESM4", "GFDL-ESM4"])],
            None
        )
        .contains("twice")
    );
    assert!(
        err(
            vec![
                scenario("2041-2070", "ssp370", &ALL),
                scenario("2041-2070", "ssp370", &["GFDL-ESM4"])
            ],
            None
        )
        .contains("twice")
    );
    let m = err(
        vec![
            scenario("2041-2070", "ssp126", &ALL),
            scenario("2041-2070", "ssp370", &ALL),
            scenario("2041-2070", "ssp585", &ALL),
            scenario("2071-2100", "ssp585", &["GFDL-ESM4"]),
        ],
        None,
    );
    assert!(
        m.contains("at most 15") && m.contains("16 requested"),
        "{m}"
    );
    assert!(
        err(
            vec![scenario("2041-2070", "ssp370", &ALL)],
            Some(vec!["demo_rugged"])
        )
        .contains("climate")
    );
    // The largest allowed request is accepted.
    e.submit(spec(
        "maxent",
        vec![
            scenario("2041-2070", "ssp126", &ALL),
            scenario("2041-2070", "ssp370", &ALL),
            scenario("2041-2070", "ssp585", &ALL),
        ],
    ))
    .expect("15 runs accepted");
    let _ = std::fs::remove_dir_all(dir);
}

/// Real CHELSA v2.1 CMIP6 layers on a small window of Provence (1° box), a virtual species on
/// the real present climate, one scenario under the five GCMs. Prints timings and bytes.
/// `cargo test --release -p niche-app --test projections -- --ignored --nocapture`
#[test]
#[ignore = "network"]
fn live_chelsa_future_projection_of_a_virtual_species() {
    use niche_app::env;
    use niche_app::fit::{Projector, fit_species};
    let dir = root("live");
    let http = niche_data::Http::new();
    let (w, s, e, n) = (5.0, 43.5, 6.0, 44.5);
    let area = StudyArea {
        name: "Provence 1° box".into(),
        geometry: serde_json::json!({"type": "Polygon", "coordinates": [[[w, s], [e, s], [e, n], [w, n], [w, s]]]}),
        places: vec![],
    };
    let layers: Vec<String> = ["chelsa_bio1", "chelsa_bio4", "chelsa_bio12", "chelsa_bio15"]
        .iter()
        .map(|s| (*s).to_string())
        .collect();
    let t = std::time::Instant::now();
    let stack = env::build_stack(&http, &dir, &area, &layers, 1, false, &|_, _| {}).expect("stack");
    let present_bytes = http.range_bytes_received();
    println!(
        "present stack: {} × {} cells, {} valid, {:.1} s, {:.2} MB range reads",
        stack.spec.width,
        stack.spec.height,
        stack.valid.iter().filter(|v| **v).count(),
        t.elapsed().as_secs_f64(),
        present_bytes as f64 / 1e6
    );
    // Virtual species: suitable where BIO1 is within ±2.5 °C of 11 °C (synthetic presences).
    let bio1 = &stack.layers[0].data;
    let cells: Vec<usize> = (0..stack.spec.len()).filter(|&i| stack.valid[i]).collect();
    let presences: Vec<usize> = cells
        .iter()
        .copied()
        .filter(|&i| (bio1[i] - 11.0).abs() < 2.5)
        .step_by(7)
        .take(150)
        .collect();
    let background: Vec<usize> = cells.iter().copied().step_by(3).take(5000).collect();
    let model = ModelSettings {
        tuning: "fixed".into(),
        feature_classes: vec!["LQ".into()],
        beta_multipliers: vec![1.0],
        ..ModelSettings::default()
    };
    let out = fit_species(
        &stack,
        &SpeciesRef {
            key: 1,
            scientific_name: "Virtualis provincialis (synthetic)".into(),
            own: None,
        },
        &presences,
        &background,
        &model,
        &ValidationSettings::default(),
        42,
        None,
        None,
        &AtomicBool::new(false),
        &|_, _| {},
    )
    .expect("fit");
    let p10 = out
        .result
        .thresholds
        .iter()
        .find(|t| t.rule == "p10")
        .expect("p10")
        .threshold;
    let projector = Projector {
        algorithm: "maxent".into(),
        vars: out.variable_ids.clone(),
        maxent: out.model.clone(),
        forest: None,
        presence: presences.clone(),
        background: background.clone(),
        p10,
    };
    let prepared = projector.prepare(&stack).expect("prepare");
    let p = scenario("2041-2070", "ssp370", &ALL);
    let mut spec = spec("maxent", vec![p.clone()]);
    spec.demo = false;
    spec.area = area.clone();
    spec.layers = layers.clone();
    spec.resolution_factor = 1;
    let mut runs = Vec::new();
    for pass in ["fresh", "cached"] {
        runs.clear();
        let before = http.range_bytes_received();
        let t = std::time::Instant::now();
        for gcm in &p.gcms {
            let tg = std::time::Instant::now();
            let (future, urls) = projection::future_layers(
                &http,
                &dir,
                &spec,
                &stack,
                &projector.vars,
                &p.period,
                &p.ssp,
                gcm,
            )
            .expect("future layers");
            let read = tg.elapsed().as_secs_f64();
            let run = prepared.predict(future).expect("predict");
            println!(
                "  {pass} {gcm}: {} layers read in {read:.2} s, predicted in {:.3} s",
                urls.len(),
                tg.elapsed().as_secs_f64() - read
            );
            runs.push(run);
        }
        println!(
            "{pass}: 5 GCMs in {:.1} s, {:.2} MB range reads",
            t.elapsed().as_secs_f64(),
            (http.range_bytes_received() - before) as f64 / 1e6
        );
    }
    let agg = projection::aggregate(
        stack.spec.len(),
        &prepared.cells,
        &|c| stack.cell_area(c),
        &prepared.present,
        prepared.threshold,
        &p,
        &runs,
    );
    let s = &agg.summary;
    println!(
        "{} {}: present suitable {:.0} km², future {:.0} km² (stable {:.0}, gained {:.0}, lost {:.0}), missing cells {}, MESS<0 {:.1} %, mean SD {:.3}",
        s.period,
        s.ssp,
        s.present_suitable_km2,
        s.future_suitable_km2,
        s.stable_km2,
        s.gained_km2,
        s.lost_km2,
        s.cells_missing,
        s.novel_fraction * 100.0,
        s.mean_gcm_sd
    );
    for g in &s.per_gcm {
        println!(
            "  {:<14} future {:>6.0} km², MESS<0 {:>5.1} %",
            g.gcm,
            g.future_suitable_km2,
            g.novel_fraction * 100.0
        );
    }
    assert_eq!(s.cells_missing, 0, "no future NaN on land cells of the box");
    assert!((s.present_suitable_km2 + 0.0) > 0.0);
    let _ = std::fs::remove_dir_all(dir);
}

//! Second modelling engine (ADR-0017, Science v1 phase 6) on the synthetic demo: down-sampled
//! random forest and the MaxEnt + RF ensemble as opt-in algorithms. MaxEnt specifications must
//! stay bit-identical; the new algorithms must run through the whole pipeline (CV, null models,
//! AOA, thresholds, reports, manifest) and resume after an interruption with identical outputs.

use std::collections::BTreeMap;
use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::Duration;

use niche_app::dto::*;
use niche_app::{Config, Engine, demo};

fn cfg(dir: &std::path::Path) -> Config {
    Config {
        data_dir: dir.join("data"),
        cache_dir: dir.join("cache"),
        max_records: 5000,
        gbif: None,
        secret_key: None,
        mirror: None,
        limits: Default::default(),
        retention_days: 0,
    }
}

fn root(name: &str) -> std::path::PathBuf {
    let d = std::env::temp_dir().join(format!("niche-rf-engine-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&d);
    d
}

/// A small, fast demo study (one fixed MaxEnt setting, coarser grid).
fn spec(model: ModelSettings, validation: ValidationSettings) -> JobSpec {
    JobSpec {
        name: "second engine".into(),
        species: vec![SpeciesRef {
            key: 0,
            scientific_name: demo::SPECIES_NAME.into(),
            own: None,
        }],
        area: StudyArea {
            name: "Demo".into(),
            geometry: demo::area_geojson(),
            places: vec![],
        },
        layers: demo::LAYERS.iter().map(|l| l.0.to_string()).collect(),
        resolution_factor: 2,
        filters: OccurrenceFilters::default(),
        model,
        validation,
        seed: 5,
        demo: true,
        projections: vec![],
        own_dataset: None,
    }
}

fn model(algorithm: &str, trees: Option<usize>) -> ModelSettings {
    ModelSettings {
        tuning: "fixed".into(),
        feature_classes: vec!["LQ".into()],
        beta_multipliers: vec![1.0],
        background_points: 2000,
        algorithm: algorithm.into(),
        rf_trees: trees,
        ..ModelSettings::default()
    }
}

type Files = BTreeMap<String, Vec<u8>>;

/// Output files of a species, report generation times removed (the only content allowed to
/// differ between runs).
fn outputs(dir: &std::path::Path) -> Files {
    std::fs::read_dir(dir)
        .expect("species dir")
        .flatten()
        .map(|e| {
            let name = e.file_name().to_string_lossy().into_owned();
            let mut bytes = std::fs::read(e.path()).expect("read");
            if name == "report.md" || name == "report.html" {
                let text = String::from_utf8(bytes).expect("utf-8");
                bytes = text
                    .lines()
                    .filter(|l| !l.starts_with("Generated by NicheRS"))
                    .map(|l| {
                        match (
                            l.find(" · Generated by NicheRS"),
                            l.find(" · GBIF taxon key"),
                        ) {
                            (Some(a), Some(b)) if a < b => format!("{}{}", &l[..a], &l[b..]),
                            _ => l.to_string(),
                        }
                    })
                    .collect::<Vec<_>>()
                    .join("\n")
                    .into_bytes();
            }
            (name, bytes)
        })
        .collect()
}

fn run(dir: &std::path::Path, spec: JobSpec) -> (Engine, String, SpeciesResult, Files) {
    let e = Engine::open(cfg(dir)).expect("engine");
    let id = e.submit(spec).expect("submit").id;
    let never = AtomicBool::new(false);
    e.run_job(&id, &never, &never);
    let res = e.results(&id).expect("results");
    assert_eq!(res.job.status, JobStatus::Succeeded, "{:?}", res.job.error);
    let r = res.species[0].clone();
    assert_eq!(r.status, SpeciesRunStatus::Succeeded, "{:?}", r.error);
    let files = outputs(&dir.join("data/jobs").join(&id).join("0"));
    (e, id, r, files)
}

fn text(files: &Files, name: &str) -> String {
    String::from_utf8(files[name].clone()).expect("utf-8")
}

#[test]
fn maxent_specifications_keep_their_wire_form_and_outputs() {
    // The pre-ADR-0017 wire form, and the same settings with the algorithm written explicitly.
    let old: ModelSettings = serde_json::from_str(
        r#"{"tuning":"fixed","feature_classes":["LQ"],"beta_multipliers":[1.0],"background_points":2000,"collinearity_threshold":0.7}"#,
    )
    .expect("old form");
    let explicit: ModelSettings = serde_json::from_str(
        r#"{"tuning":"fixed","feature_classes":["LQ"],"beta_multipliers":[1.0],"background_points":2000,"collinearity_threshold":0.7,"algorithm":"maxent","rf_tune_mtry":false}"#,
    )
    .expect("explicit form");
    assert_eq!(old, explicit);
    assert_eq!(old, model("maxent", None));
    // No new key in the JSON (hence the same spec hash) for MaxEnt.
    let json = serde_json::to_string(&explicit).expect("json");
    assert!(
        !json.contains("algorithm") && !json.contains("rf_"),
        "{json}"
    );

    let dir = root("maxent");
    let (e, id, r, files) = run(&dir, spec(old, ValidationSettings::default()));
    assert!(r.selected.algorithm.is_none() && r.selected.rf_trees.is_none());
    assert_eq!(r.selected.algorithm(), "maxent");
    assert!(r.partial_dependence.is_empty() && r.validation.members.is_empty());
    assert!(r.contributions.iter().all(|c| c.rf_importance.is_none()));
    assert!(
        r.tuning
            .iter()
            .all(|t| t.algorithm.is_none() && t.mtry.is_none())
    );
    assert!(files.contains_key("model.lambdas"));
    for f in ["model.rf.json", "partial_dependence.csv"] {
        assert!(!files.contains_key(f), "{f} in a MaxEnt result");
    }
    let result = text(&files, "result.json");
    for key in [
        "\"algorithm\"",
        "rf_",
        "\"partial_dependence\"",
        "\"members\"",
        "\"mtry\"",
    ] {
        assert!(!result.contains(key), "{key} in a MaxEnt result.json");
    }
    let md = text(&files, "report.md");
    assert!(!md.contains("random forest") && !md.contains("Breiman"));
    let m = e.manifest(&id).expect("manifest");
    assert_eq!(m["methods"]["algorithm"], "MaxEnt (cloglog output)");
    assert!(m["methods"].get("random_forest").is_none());
    assert_eq!(m["software"]["engine"], "niche-maxent (MaxEnt 3.4.4 port)");
    // A result.json written before ADR-0017 still loads (the new fields are optional).
    let mut v: serde_json::Value = serde_json::from_str(&result).expect("json");
    for c in v["contributions"].as_array_mut().expect("contributions") {
        c.as_object_mut().expect("object").remove("rf_importance");
    }
    let back: SpeciesResult = serde_json::from_value(v).expect("old result loads");
    assert_eq!(back, r);
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn random_forest_on_the_demo() {
    let dir = root("rf");
    let t = std::time::Instant::now();
    let (e, id, r, files) = run(&dir, spec(model("rf", None), ValidationSettings::default()));
    println!(
        "demo (factor 2, 2000 background, {} trees): RF study {:.1} s",
        DEFAULT_RF_TREES,
        t.elapsed().as_secs_f64()
    );
    let v = &r.validation;
    println!(
        "RF: Boyce {:?}, OR10 {:.3}, AUC {:.3}, evidence {:?}, selected {:?}",
        v.cbi_mean, v.or10_mean, v.auc_mean, r.evidence.level, r.selected
    );
    // Better than random under spatial blocks (on this demo, where held-out blocks need
    // extrapolation, the forest is weaker than MaxEnt: Boyce 0.22 vs 0.57, AUC 0.57 vs 0.66;
    // with random k-fold the two are comparable). Omission at the P10 threshold of the
    // out-of-bag training scores is near its nominal 0.10, not ≈ 1 as with in-bag predictions.
    assert!(v.cbi_mean.is_some_and(|c| c > 0.1), "{:?}", v.cbi_mean);
    assert!(v.auc_mean > 0.55, "AUC {}", v.auc_mean);
    assert!(v.or10_mean < 0.25, "OR10 {}", v.or10_mean);
    assert_eq!(v.folds.len(), 4);
    // Selected setting and tuning table.
    assert_eq!(r.selected.algorithm.as_deref(), Some("rf"));
    assert_eq!(r.selected.rf_trees, Some(DEFAULT_RF_TREES));
    let p = r.variables_used.len();
    assert_eq!(
        r.selected.rf_mtry,
        Some(((p as f64).sqrt() as usize).max(1))
    );
    assert!(r.selected.rf_seed.is_some());
    assert_eq!(r.tuning.len(), 1);
    assert_eq!(r.tuning[0].algorithm.as_deref(), Some("rf"));
    assert!(r.tuning[0].selected);
    // Explanations: RF importance only, partial dependence instead of MaxEnt curves.
    assert_eq!(r.contributions.len(), p);
    assert!(
        r.contributions
            .iter()
            .all(|c| { c.permutation_importance.is_none() && c.rf_importance == Some(c.percent) })
    );
    let total: f64 = r.contributions.iter().map(|c| c.percent).sum();
    assert!((total - 100.0).abs() < 1e-6, "importance sums to {total}");
    assert!(r.response_curves.is_empty());
    assert_eq!(r.partial_dependence.len(), p);
    for c in &r.partial_dependence {
        assert_eq!(c.x.len(), 51);
        assert!(c.y.iter().all(|y| (0.0..=1.0).contains(y)));
        assert_eq!(c.x[0], c.training_min);
    }
    // Map in [0, 1], thresholds on the same scale, areas consistent.
    let s = e.raster(&id, 0, "suitability").expect("suitability");
    assert!(
        s.data
            .iter()
            .filter(|x| x.is_finite())
            .all(|x| (0.0..=1.0).contains(x))
    );
    assert_eq!(r.thresholds.len(), 3);
    for t in &r.thresholds {
        assert!((0.0..=1.0).contains(&t.threshold));
        assert!(t.area_km2 > 0.0 && t.fraction_of_study_area <= 1.0);
    }
    assert!(r.uncertainty.mean_fold_sd.is_finite() && r.uncertainty.mean_fold_sd > 0.0);
    // Files: forest instead of lambdas; descriptions say "not a probability".
    assert!(!files.contains_key("model.lambdas") && !files.contains_key("response_curves.csv"));
    let forest = &files["model.rf.json"];
    println!("model.rf.json: {} bytes", forest.len());
    let f: serde_json::Value = serde_json::from_slice(forest).expect("forest JSON");
    assert_eq!(f["trees"].as_array().map(Vec::len), Some(DEFAULT_RF_TREES));
    assert_eq!(f["settings"]["seed"], r.selected.rf_seed.expect("seed"));
    assert!(text(&files, "partial_dependence.csv").starts_with("variable,x,y\n"));
    let desc = &r
        .files
        .iter()
        .find(|f| f.name == "suitability.tif")
        .expect("suitability")
        .description;
    assert!(desc.contains("NOT a probability") && desc.contains("trees voting"));
    // Reports: method, references, output semantics.
    let md = text(&files, "report.md");
    for t in [
        "down-sampled (balanced) random forest",
        "## Predictor importance",
        "## References (random forest)",
        "Breiman, L. (2001)",
        "Ecography 44, 1731–1742",
        "relative suitability index",
        "not a probability",
    ] {
        assert!(md.contains(t), "report.md lacks {t}");
    }
    let html = text(&files, "report.html");
    for t in [
        "Partial dependence (random forest)",
        "model.rf.json",
        "Valavi, R., Elith, J.",
        "trees voting presence",
    ] {
        assert!(html.contains(t), "report.html lacks {t}");
    }
    assert!(!html.contains("cloglog transform") && !html.contains("confidence"));
    assert!(!html.contains("probability of presence</b>"));
    // Manifest: algorithm, RF settings and seed.
    let m = e.manifest(&id).expect("manifest");
    assert_eq!(m["spec"]["model"]["algorithm"], "rf");
    assert!(
        m["methods"]["algorithm"]
            .as_str()
            .is_some_and(|a| a.contains("random forest"))
    );
    assert_eq!(m["methods"]["random_forest"]["trees"], DEFAULT_RF_TREES);
    assert_eq!(
        m["species"][0]["selected"]["rf_seed"],
        r.selected.rf_seed.expect("seed")
    );
    assert!(m["species"][0]["artifacts"]["model.rf.json"]["sha256"].is_string());
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn ensemble_on_the_demo() {
    let dir = root("ensemble");
    let t = std::time::Instant::now();
    let mut settings = model("ensemble", Some(200));
    settings.rf_tune_mtry = true;
    let (e, id, r, files) = run(&dir, spec(settings, ValidationSettings::default()));
    println!(
        "demo ensemble (200 trees, mtry tuned): {:.1} s",
        t.elapsed().as_secs_f64()
    );
    let v = &r.validation;
    println!(
        "ensemble: Boyce {:?}, OR10 {:.3}, AUC {:.3}; members {:?}; evidence {:?}",
        v.cbi_mean, v.or10_mean, v.auc_mean, v.members, r.evidence.level
    );
    assert_eq!(r.selected.algorithm.as_deref(), Some("ensemble"));
    assert_eq!(r.selected.feature_classes, "LQ");
    assert_eq!(r.selected.rf_trees, Some(200));
    // Members: MaxEnt and RF metrics on the same folds; the ensemble's own metrics differ.
    assert_eq!(
        v.members
            .iter()
            .map(|m| m.algorithm.as_str())
            .collect::<Vec<_>>(),
        ["maxent", "rf"]
    );
    assert!(v.cbi_mean.is_some_and(|c| c > 0.4), "{:?}", v.cbi_mean);
    assert!(v.auc_mean > 0.6, "AUC {}", v.auc_mean);
    // The ensemble's AUC lies near its members' (ranks averaged).
    let lo = v
        .members
        .iter()
        .map(|m| m.auc_mean)
        .fold(f64::INFINITY, f64::min);
    assert!(
        v.auc_mean > lo - 0.05,
        "{} vs members {:?}",
        v.auc_mean,
        v.members
    );
    // Tuning: one MaxEnt row, two RF rows (floor(sqrt p) and floor(p/2) differ for p ≥ 4), one
    // selected per member.
    let p = r.variables_used.len();
    let rf_rows = r.tuning.iter().filter(|t| t.mtry.is_some()).count();
    assert_eq!(
        rf_rows,
        if p / 2 != ((p as f64).sqrt() as usize).max(1) {
            2
        } else {
            1
        }
    );
    assert_eq!(r.tuning.iter().filter(|t| t.selected).count(), 2);
    // Both members' explanations.
    assert!(!r.response_curves.is_empty() && !r.partial_dependence.is_empty());
    assert!(
        r.contributions
            .iter()
            .all(|c| c.permutation_importance.is_some() && c.rf_importance.is_some())
    );
    for f in [
        "model.lambdas",
        "model.rf.json",
        "response_curves.csv",
        "partial_dependence.csv",
    ] {
        assert!(files.contains_key(f), "{f} missing");
    }
    let s = e.raster(&id, 0, "suitability").expect("suitability");
    let vals: Vec<f32> = s.data.iter().copied().filter(|x| x.is_finite()).collect();
    assert!(vals.iter().all(|x| (0.0..=1.0).contains(x)));
    // Ranks over the background: the study-area mean is near 0.5.
    let mean = vals.iter().map(|&x| f64::from(x)).sum::<f64>() / vals.len() as f64;
    assert!((mean - 0.5).abs() < 0.1, "mean ensemble value {mean}");
    let md = text(&files, "report.md");
    for t in [
        "percentile rank",
        "Valavi, R., Guillera-Arroita",
        "Members on the same folds",
    ] {
        assert!(md.contains(t), "report.md lacks {t}");
    }
    let m = e.manifest(&id).expect("manifest");
    assert!(m["methods"]["ensemble"].is_string());
    assert!(
        m["methods"]["random_forest"]["mtry"]
            .as_str()
            .is_some_and(|x| x.contains("p/2"))
    );
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn random_forest_with_null_models_and_aoa() {
    let dir = root("rf-nulls");
    let validation = ValidationSettings {
        null_models: 19,
        aoa: true,
        ..ValidationSettings::default()
    };
    let t = std::time::Instant::now();
    let (_, _, r, files) = run(&dir, spec(model("rf", Some(100)), validation));
    println!(
        "demo RF (100 trees) + 19 null models + AOA: {:.1} s",
        t.elapsed().as_secs_f64()
    );
    let nm = r.validation.null_model.as_ref().expect("null models");
    println!("null models {nm:?}");
    assert_eq!((nm.requested, nm.completed), (19, 19));
    assert_eq!(nm.cbi.observed, r.validation.cbi_mean);
    assert!(nm.cbi.p_value > 0.0 && nm.cbi.p_value <= 1.0);
    let a = r.aoa.as_ref().expect("aoa");
    assert_eq!(a.n_train, r.data.presences + r.data.background);
    // AOA weights are the RF permutation importance, normalised.
    for w in &a.weights {
        let c = r
            .contributions
            .iter()
            .find(|c| c.variable == w.variable)
            .expect("contribution");
        assert!(
            (w.weight - c.percent / 100.0).abs() < 1e-9,
            "{w:?} vs {c:?}"
        );
    }
    assert!(files.contains_key("aoa.tif"));
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn interrupted_random_forest_study_resumes_with_identical_outputs() {
    let dir = root("resume");
    let mut settings = model("ensemble", Some(150));
    settings.rf_tune_mtry = true;
    let s = spec(
        settings,
        ValidationSettings {
            null_models: 19,
            ..ValidationSettings::default()
        },
    );
    let never = AtomicBool::new(false);
    let (_, _, _, reference) = run(&dir.join("reference"), s.clone());

    let d = dir.join("resumed");
    let id;
    let ckpt;
    {
        let e = Arc::new(Engine::open(cfg(&d)).expect("engine"));
        id = e.submit(s).expect("submit").id;
        ckpt = d.join("data/jobs").join(&id).join("checkpoints/0");
        let stop = Arc::new(AtomicBool::new(false));
        let finished = Arc::new(AtomicBool::new(false));
        let (s2, f2, c2) = (stop.clone(), finished.clone(), ckpt.clone());
        // Stop once random-forest fold checkpoints and some null models exist.
        let watcher = std::thread::spawn(move || {
            while !f2.load(Ordering::Relaxed) {
                let names: Vec<String> = std::fs::read_dir(&c2)
                    .map(|d| {
                        d.flatten()
                            .map(|e| e.file_name().to_string_lossy().into_owned())
                            .collect()
                    })
                    .unwrap_or_default();
                let rf = names.iter().filter(|n| n.starts_with("cv-rf-")).count();
                let nulls = names.iter().filter(|n| n.starts_with("null-")).count();
                if rf >= 2 && nulls >= 10 {
                    s2.store(true, Ordering::Relaxed);
                    return;
                }
                std::thread::sleep(Duration::from_millis(1));
            }
        });
        e.run_job(&id, &stop, &stop);
        finished.store(true, Ordering::Relaxed);
        watcher.join().expect("watcher");
        assert!(
            stop.load(Ordering::Relaxed),
            "the study was not interrupted"
        );
        assert_eq!(
            e.store().get(&id).expect("db").expect("job").status,
            JobStatus::Running,
            "shutdown leaves the job resumable"
        );
    }
    assert!(ckpt.exists(), "checkpoints kept for the resume");
    let e = Engine::open(cfg(&d)).expect("engine");
    e.store().recover_interrupted().expect("recover");
    e.run_job(&id, &never, &never);
    let res = e.results(&id).expect("results");
    assert_eq!(res.job.status, JobStatus::Succeeded);
    // Fold metrics of the forests came from checkpoints (the selected forests were refitted).
    let events = e.store().events_after(&id, 0).expect("events");
    assert!(
        events.iter().any(|ev| ev.message.contains("resumed with")),
        "no resumed cross-validation models"
    );
    let resumed = outputs(&d.join("data/jobs").join(&id).join("0"));
    assert_eq!(
        reference.keys().collect::<Vec<_>>(),
        resumed.keys().collect::<Vec<_>>()
    );
    for (name, bytes) in &reference {
        assert!(resumed[name] == *bytes, "{name} differs after resuming");
    }
    let _ = std::fs::remove_dir_all(dir);
}


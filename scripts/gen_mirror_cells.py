"""Generate crates/niche-data/src/gbif_mirror_cells.rs: the cells of the regional GBIF mirror.

Usage (Natural Earth 1:10m v5.1.2 GeoJSON, public domain, downloaded beforehand):
    uv run --with shapely python -I scripts/gen_mirror_cells.py \
        ne_10m_admin_0_countries.geojson ne_10m_land.geojson > crates/niche-data/src/gbif_mirror_cells.rs

Region cells: STEP-degree cells intersecting the land of metropolitan France (with Corsica),
Spain (with the Balearic and Canary Islands, Ceuta and Melilla), Andorra and Monaco, buffered by
BUFFER degrees. The mirror's GBIF download covers exactly these cells.
Sea cells: cells in the same frame that touch no land of any country (land buffered by 0.02°).
A study area may cross them: records at sea are excluded by cleaning, so the mirror still holds
every record a model can use.
"""
import json, math, sys
from shapely.geometry import MultiPolygon, box, shape
from shapely.geometry.polygon import orient
from shapely.ops import unary_union
from shapely.strtree import STRtree

STEP, BUFFER = 0.5, 0.1
FRAME = (-20.0, 26.0, 11.0, 53.0)
countries, land = (json.load(open(p)) for p in sys.argv[1:3])

parts = []
for f in countries["features"]:
    iso = f["properties"].get("ADM0_A3")
    if iso not in {"FRA", "ESP", "AND", "MCO"}:
        continue
    g = shape(f["geometry"])
    for q in g.geoms if g.geom_type == "MultiPolygon" else [g]:
        c = q.representative_point()
        if iso == "FRA" and not (-6 < c.x < 10 and 41 < c.y < 52):
            continue  # overseas France is not mirrored
        parts.append(q)
region = unary_union(parts).buffer(BUFFER)

def cells(pred, frame):
    w, s, e, n = frame
    return [(i, j)
            for i in range(math.floor(w / STEP), math.ceil(e / STEP))
            for j in range(math.floor(s / STEP), math.ceil(n / STEP))
            if pred(box(i * STEP, j * STEP, (i + 1) * STEP, (j + 1) * STEP))]

region_cells = cells(region.intersects, region.bounds)
w, s, e, n = FRAME
lands = [q.buffer(0.02) for f in land["features"] for g in [shape(f["geometry"])]
         for q in (g.geoms if g.geom_type == "MultiPolygon" else [g]) if q.intersects(box(w - 1, s - 1, e + 1, n + 1))]
tree = STRtree(lands)
sea_cells = cells(lambda b: not any(lands[k].intersects(b) for k in tree.query(b)), FRAME)

# The download geometry: the union of the region cells as valid polygons (cells sharing edges are
# not a valid MULTIPOLYGON for GBIF), exterior rings counter-clockwise, holes clockwise.
union = unary_union([box(i * STEP, j * STEP, (i + 1) * STEP, (j + 1) * STEP) for i, j in region_cells]).simplify(0)
polys = [orient(p, 1.0) for p in (union.geoms if union.geom_type == "MultiPolygon" else [union])]
assert all(p.is_valid for p in polys)
def ring(r):
    return "(" + ",".join(f"{x:g} {y:g}" for x, y in r.coords) + ")"
wkt = "MULTIPOLYGON(" + ",".join("(" + ",".join([ring(p.exterior)] + [ring(h) for h in p.interiors]) + ")" for p in polys) + ")"
assert MultiPolygon(polys).is_valid

def rs(name, cs):
    cs = sorted(cs)
    rows = [", ".join(f"({i}, {j})" for i, j in cs[k:k + 8]) + "," for k in range(0, len(cs), 8)]
    return f"    {name}: &[\n" + "\n".join("        " + r for r in rows) + "\n    ],"

print(f"""//! Cells of the regional mirrors. Generated by `scripts/gen_mirror_cells.py`; do not edit.
//!
//! FR-ES: {STEP}° cells intersecting the land of metropolitan France (with Corsica), Spain (with
//! the Balearic and Canary Islands, Ceuta and Melilla), Andorra and Monaco, buffered by {BUFFER}°
//! (~10 km); sea cells touch no land of any country. Natural Earth 1:10m v5.1.2 (public domain).

use crate::gbif_mirror::Region;

pub const FR_ES: Region = Region {{
    id: "fr-es",
    name: "France (metropolitan) and Spain",
    step: {STEP},
{rs("cells", region_cells)}
{rs("sea", sea_cells)}
    wkt: "{wkt}",
}};""")
